# -*- coding: utf-8 -*-
"""Классификатор обращений: категория + черновик ответа.
Запуск: python3 classify.py
"""

ЖАЛОБА_СЛОВА = ["очеред", "холодн", "пропал", "не работает", "сломал",
                "грязн", "долго", "шум", "плох"]
СПРАВКА_СЛОВА = ["как ", "где ", "справк", "записаться", "консультац",
                 "парковк", "расписан", "когда ", "докумен"]

ОТВЕТЫ = {
    "справка": (
        "Здравствуйте! Спасибо за обращение. Подготовим для вас информацию "
        "и ответим в течение рабочего дня. Если нужно срочно — напишите, "
        "пожалуйста, ваши контакты."
    ),
    "жалоба": (
        "Здравствуйте! Спасибо, что сообщили — извините за неудобство. "
        "Передали вопрос ответственной службе, вернёмся с решением "
        "в течение рабочего дня."
    ),
    "другое": (
        "Здравствуйте! Приняли ваше обращение. Уточните, пожалуйста, детали — "
        "так мы ответим точнее и быстрее."
    ),
}


def категория(текст):
    t = текст.lower()
    for слово in ЖАЛОБА_СЛОВА:
        if слово in t:
            return "жалоба"
    for слово in СПРАВКА_СЛОВА:
        if слово in t:
            return "справка"
    return "другое"


def main():
    with open("messages.txt", encoding="utf-8") as f:
        обращения = [s.strip() for s in f if s.strip()]

    for i, текст in enumerate(обращения, 1):
        кат = категория(текст)
        print(f"{i}. Обращение: {текст}")
        print(f"   Категория: {кат}")
        print(f"   Черновик ответа: {ОТВЕТЫ[кат]}")
        print()


if __name__ == "__main__":
    main()
